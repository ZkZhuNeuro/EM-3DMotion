function result = SaveGaussianStimOverallR2Scatter(analysis, options)
%SAVEGAUSSIANSTIMOVERALLR2SCATTER Compare repeat-wise nested-CV R-squared.
% Each point is one complete outer-CV repeat: all sessions are predicted
% once in that repeat. The signed-rank test describes robustness to random
% fold assignment; repeats reuse the same sessions and are not independent
% population samples.

arguments
    analysis (1, 1) struct
    options.OutputFolder (1, 1) string = ""
    options.FigureVisible (1, 1) logical = false
    options.PointColor double = []
end

if strlength(options.OutputFolder) == 0
    options.OutputFolder = string(analysis.OutputFolder);
end
required = {'Robustness', 'Area', 'UnitType', 'SessionCount'};
if ~all(isfield(analysis, required)) || ...
        ~isfield(analysis.Robustness, 'RepeatMetrics')
    error('GaussianStimR2Scatter:InvalidAnalysis', ...
        'Analysis does not contain outer-repeat robustness metrics.');
end
rows = analysis.Robustness.RepeatMetrics;
rows = rows(rows.Condition == "Equal-cue aggregate", :);
rows = sortrows(rows, 'Repeat');
if height(rows) < 2 || numel(unique(rows.Repeat)) ~= height(rows) || ...
        any(~isfinite(rows.StimOnlyCVR2)) || any(~isfinite(rows.GaussianCVR2))
    error('GaussianStimR2Scatter:InvalidPairs', ...
        'Expected at least two unique finite outer-repeat R-squared pairs.');
end

originalR2 = double(rows.StimOnlyCVR2);
gaussianR2 = double(rows.GaussianCVR2);
deltaR2 = gaussianR2 - originalR2;
[pTwoSided, hTwoSided, twoSidedStats] = signrank( ...
    gaussianR2, originalR2, 'tail', 'both', 'method', 'approximate');
[pGaussianGreater, hGaussianGreater, greaterStats] = signrank( ...
    gaussianR2, originalR2, 'tail', 'right', 'method', 'approximate');

pairs = table(rows.Repeat, originalR2, gaussianR2, deltaR2, ...
    gaussianR2 > originalR2, 'VariableNames', ...
    {'OuterRepeat', 'StimOnlyR2', 'GaussianOptimalR2', 'DeltaR2', ...
    'GaussianImproved'});
summary = table(height(pairs), analysis.SessionCount, ...
    mean(originalR2), mean(gaussianR2), median(originalR2), ...
    median(gaussianR2), mean(deltaR2), median(deltaR2), ...
    nnz(deltaR2 > 0), mean(deltaR2 > 0), ...
    pTwoSided, logical(hTwoSided), twoSidedStats.signedrank, ...
    twoSidedStats.zval, pGaussianGreater, logical(hGaussianGreater), ...
    greaterStats.signedrank, greaterStats.zval, ...
    'VariableNames', {'NumOuterRepeats', 'NumSessions', ...
    'MeanStimOnlyR2', 'MeanGaussianOptimalR2', 'MedianStimOnlyR2', ...
    'MedianGaussianOptimalR2', 'MeanDeltaR2', 'MedianDeltaR2', ...
    'RepeatsGaussianImproved', 'FractionRepeatsGaussianImproved', ...
    'SignedRankPTwoSided', 'SignedRankRejectTwoSided', ...
    'SignedRankStatisticTwoSided', 'SignedRankZTwoSided', ...
    'SignedRankPGaussianGreater', 'SignedRankRejectGaussianGreater', ...
    'SignedRankStatisticGaussianGreater', 'SignedRankZGaussianGreater'});

if ~isfolder(options.OutputFolder)
    mkdir(options.OutputFolder);
end
writetable(pairs, fullfile(options.OutputFolder, ...
    'OverallR2OuterRepeatPairs.csv'));
writetable(summary, fullfile(options.OutputFolder, ...
    'OverallR2SignedRank.csv'));

visibility = ternary(options.FigureVisible, 'on', 'off');
figureHandle = figure('Color', 'w', 'Visible', visibility, ...
    'Position', [120 120 760 700], ...
    'Name', 'Overall nested-CV R-squared comparison');
hold on
allValues = [originalR2; gaussianR2];
limits = [min(allValues), max(allValues)];
span = diff(limits);
if ~isfinite(span) || span <= eps(max(1, abs(mean(limits))))
    span = 1;
end
limits = limits + [-1 1] .* max(0.02, 0.12 .* span);
identity = plot(limits, limits, 'k--', 'LineWidth', 1.5, ...
    'DisplayName', 'Identity');
if isempty(options.PointColor)
    points = scatter(originalR2, gaussianR2, 58, deltaR2, 'filled', ...
        'MarkerEdgeColor', [0.15 0.15 0.15], 'LineWidth', 0.8, ...
        'DisplayName', 'Outer-CV repeat');
    colormap(turbo);
    colorBar = colorbar;
    colorBar.Label.String = '\DeltaR^2 (Gaussian - stim only)';
else
    if ~isequal(size(options.PointColor), [1 3]) || ...
            any(~isfinite(options.PointColor)) || ...
            any(options.PointColor < 0 | options.PointColor > 1)
        error('GaussianStimR2Scatter:PointColor', ...
            'PointColor must be an RGB triplet between zero and one.');
    end
    points = scatter(originalR2, gaussianR2, 58, ...
        options.PointColor, 'filled', ...
        'MarkerEdgeColor', [0.15 0.15 0.15], 'LineWidth', 0.8, ...
        'DisplayName', 'Outer-CV repeat');
end
xlim(limits); ylim(limits);
axis square
grid on; box on
xlabel('Stimulation-channel-only nested-CV R^2');
ylabel('Gaussian-optimal nested-CV R^2');
title(sprintf('%s %s overall prediction across %d outer-CV repeats', ...
    analysis.Area, analysis.UnitType, height(pairs)));
subtitle(sprintf(['Signed rank: two-sided p = %.3g; Gaussian > stim p = %.3g; ' ...
    'improved %d/%d'], pTwoSided, pGaussianGreater, ...
    nnz(deltaR2 > 0), height(pairs)));
legend([identity points], 'Location', 'southeast');
text(limits(1) + 0.04 .* span, limits(2) - 0.06 .* span, ...
    sprintf(['mean R^2: %.3f -> %.3f\nmedian \\DeltaR^2: %+.4f\n' ...
    'Same %d sessions reused across repeats'], ...
    mean(originalR2), mean(gaussianR2), median(deltaR2), ...
    analysis.SessionCount), 'VerticalAlignment', 'top', ...
    'BackgroundColor', 'w', 'Margin', 5);
exportgraphics(figureHandle, fullfile(options.OutputFolder, ...
    'OverallR2StimOnlyVsGaussian.png'), 'Resolution', 250);
savefig(figureHandle, fullfile(options.OutputFolder, ...
    'OverallR2StimOnlyVsGaussian.fig'));
if ~options.FigureVisible
    close(figureHandle);
end

result = struct('Pairs', pairs, 'Summary', summary, ...
    'Interpretation', [ ...
    "One paired point per complete outer-CV repeat"; ...
    "Signed-rank test is across random split realizations of the same cohort"; ...
    "It measures split robustness and does not create independent biological samples"]);
overall_r2_signed_rank = result;
save(fullfile(options.OutputFolder, 'OverallR2SignedRank.mat'), ...
    'overall_r2_signed_rank');
end


function value = ternary(condition, trueValue, falseValue)
if condition
    value = trueValue;
else
    value = falseValue;
end
end
