function result = SaveGaussianDominantAIxODAreaR2Scatters( ...
    mtAnalysis, fstAnalysis, options)
%SAVEGAUSSIANDOMINANTAIXODAREAR2SCATTERS Place MT and FST R2 pairs together.
% Each panel contains one point per complete outer-CV repeat. Colors are
% fixed by area; no performance-gradient color scale is used.

arguments
    mtAnalysis (1, 1) struct
    fstAnalysis (1, 1) struct
    options.OutputFolder (1, 1) string = ...
        "C:\EM\CurrentSpread\02_gaussian\InteractiveGaussianMetaPopulation\DominantAIxOD_MT2D_FST3D_SourceStimBothEyes"
    options.FigureVisible (1, 1) logical = false
end

mt = extractPairs(mtAnalysis, "MT");
fst = extractPairs(fstAnalysis, "FST");
allValues = [mt.StimOnlyR2; mt.GaussianR2; ...
    fst.StimOnlyR2; fst.GaussianR2];
limits = [min(allValues), max(allValues)];
span = diff(limits);
if ~isfinite(span) || span <= eps(max(1, abs(mean(limits))))
    span = 1;
end
limits = limits + [-1 1] .* max(0.02, 0.10 .* span);
if ~isfolder(options.OutputFolder)
    mkdir(options.OutputFolder);
end

figureHandle = figure('Color', 'w', ...
    'Visible', ternary(options.FigureVisible, 'on', 'off'), ...
    'Position', [80 100 1380 650], ...
    'Name', 'Dominant AI x OD nested-CV R-squared by area');
layout = tiledlayout(figureHandle, 1, 2, ...
    'TileSpacing', 'compact', 'Padding', 'compact');
mtColor = [230 126 34] ./ 255;
fstColor = [151 78 163] ./ 255;
plotPanel(nexttile(layout), mt, mtColor, limits);
plotPanel(nexttile(layout), fst, fstColor, limits);
title(layout, ['Dominant-eye AI x |OD|: Gaussian pooling versus ' ...
    'stimulation channel']);
exportgraphics(figureHandle, fullfile(options.OutputFolder, ...
    'OverallR2_MT2D_FST3D.png'), 'Resolution', 250);
savefig(figureHandle, fullfile(options.OutputFolder, ...
    'OverallR2_MT2D_FST3D.fig'));
if ~options.FigureVisible
    close(figureHandle);
end

summary = [areaSummary(mt, mtColor); areaSummary(fst, fstColor)];
pairs = [tagPairs(mt, mtColor); tagPairs(fst, fstColor)];
writetable(summary, fullfile(options.OutputFolder, ...
    'OverallR2_MT2D_FST3D_Summary.csv'));
writetable(pairs, fullfile(options.OutputFolder, ...
    'OverallR2_MT2D_FST3D_Pairs.csv'));
result = struct('Summary', summary, 'Pairs', pairs, ...
    'OutputFolder', options.OutputFolder, ...
    'FigureFile', fullfile(options.OutputFolder, ...
    'OverallR2_MT2D_FST3D.png'));
end


function data = extractPairs(analysis, expectedArea)
if ~isfield(analysis, 'PredictorMode') || ...
        string(analysis.PredictorMode) ~= "DominantAIxOD" || ...
        ~isfield(analysis, 'CohortDefinition') || ...
        string(analysis.CohortDefinition) ~= "SourceStimBothEyes_ChannelBothEyes_v1" || ...
        ~strcmpi(string(analysis.Area), expectedArea) || ...
        ~isfield(analysis, 'Robustness')
    error('GaussianAreaR2:InvalidAnalysis', ...
        'Expected a %s DominantAIxOD analysis with source both-eye-significant neurons.', expectedArea);
end
rows = analysis.Robustness.RepeatMetrics;
rows = sortrows(rows(rows.Condition == "Equal-cue aggregate", :), ...
    'Repeat');
data = struct('Area', string(analysis.Area), ...
    'UnitType', string(analysis.UnitType), ...
    'SessionCount', analysis.SessionCount, ...
    'Repeat', rows.Repeat, ...
    'StimOnlyR2', rows.StimOnlyCVR2, ...
    'GaussianR2', rows.GaussianCVR2);
data.DeltaR2 = data.GaussianR2 - data.StimOnlyR2;
[data.PTwoSided, ~, stats] = signrank( ...
    data.GaussianR2, data.StimOnlyR2, ...
    'tail', 'both', 'method', 'approximate');
data.SignedRankZ = stats.zval;
data.PGaussianGreater = signrank( ...
    data.GaussianR2, data.StimOnlyR2, ...
    'tail', 'right', 'method', 'approximate');
end


function plotPanel(axesHandle, data, color, limits)
hold(axesHandle, 'on');
plot(axesHandle, limits, limits, 'k--', 'LineWidth', 1.3);
scatter(axesHandle, data.StimOnlyR2, data.GaussianR2, ...
    48, color, 'filled', 'MarkerEdgeColor', [0.15 0.15 0.15], ...
    'LineWidth', 0.8);
xlim(axesHandle, limits); ylim(axesHandle, limits);
axis(axesHandle, 'square'); grid(axesHandle, 'on'); box(axesHandle, 'on');
xlabel(axesHandle, 'Stim-channel-only nested-CV R^2');
ylabel(axesHandle, 'Gaussian-optimal nested-CV R^2');
title(axesHandle, sprintf( ...
    '%s %s | N=%d | mean %.3f -> %.3f', ...
    data.Area, data.UnitType, data.SessionCount, ...
    mean(data.StimOnlyR2), mean(data.GaussianR2)));
subtitle(axesHandle, sprintf([ ...
    'signed rank two-sided p=%.3g | Gaussian>stim p=%.3g | ' ...
    'improved %d/%d'], data.PTwoSided, data.PGaussianGreater, ...
    nnz(data.DeltaR2 > 0), numel(data.DeltaR2)));
end


function output = areaSummary(data, color)
output = table(data.Area, data.UnitType, data.SessionCount, ...
    numel(data.Repeat), mean(data.StimOnlyR2), ...
    mean(data.GaussianR2), median(data.DeltaR2), ...
    nnz(data.DeltaR2 > 0), mean(data.DeltaR2 > 0), ...
    data.PTwoSided, data.PGaussianGreater, data.SignedRankZ, ...
    color(1), color(2), color(3), ...
    'VariableNames', {'Area', 'UnitType', 'NumSessions', ...
    'NumOuterRepeats', 'MeanStimOnlyR2', 'MeanGaussianR2', ...
    'MedianDeltaR2', 'RepeatsImproved', 'FractionRepeatsImproved', ...
    'SignedRankPTwoSided', 'SignedRankPGaussianGreater', ...
    'SignedRankZ', 'ColorR', 'ColorG', 'ColorB'});
end


function output = tagPairs(data, color)
output = table(repmat(data.Area, numel(data.Repeat), 1), ...
    repmat(data.UnitType, numel(data.Repeat), 1), ...
    data.Repeat, data.StimOnlyR2, data.GaussianR2, data.DeltaR2, ...
    data.DeltaR2 > 0, repmat(color(1), numel(data.Repeat), 1), ...
    repmat(color(2), numel(data.Repeat), 1), ...
    repmat(color(3), numel(data.Repeat), 1), ...
    'VariableNames', {'Area', 'UnitType', 'OuterRepeat', ...
    'StimOnlyR2', 'GaussianOptimalR2', 'DeltaR2', ...
    'GaussianImproved', 'ColorR', 'ColorG', 'ColorB'});
end


function value = ternary(condition, trueValue, falseValue)
if condition
    value = trueValue;
else
    value = falseValue;
end
end
