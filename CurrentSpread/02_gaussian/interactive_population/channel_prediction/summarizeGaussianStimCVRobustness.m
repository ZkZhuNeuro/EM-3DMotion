function robustness = summarizeGaussianStimCVRobustness(stim, gaussian)
%SUMMARIZEGAUSSIANSTIMCVROBUSTNESS Describe sensitivity to outer CV splits.
% One repeat pools held-out predictions over all outer folds, so every
% session is scored once per repeat. Split quantiles and the fraction of
% repeats improved are descriptive, not confidence intervals or p-values.

arguments
    stim (1, 1) struct
    gaussian (1, 1) struct
end
assert(isequal(stim.FoldAssignments, gaussian.FoldAssignments) && ...
    isequal(stim.Observed, gaussian.Observed) && ...
    isequaln(stim.NullPredictionByRepeat, gaussian.NullPredictionByRepeat), ...
    'GaussianStimCV:RobustnessUnmatched', 'Robustness summaries require paired folds, observations, and null predictions.');
stimCueMSE = stim.Nested.PerCueMSEByRepeat;
gaussianCueMSE = gaussian.Nested.PerCueMSEByRepeat;
numRepeats = size(stimCueMSE, 1);
assert(isequal(size(stimCueMSE), size(gaussianCueMSE)) && ...
    size(stimCueMSE, 2) == 4 && all(isfinite(stimCueMSE), 'all') && ...
    all(isfinite(gaussianCueMSE), 'all'), ...
    'GaussianStimCV:RobustnessSize', 'Expected matched finite repeat-by-four-cue MSEs.');

stimMSE = [mean(stimCueMSE, 2), stimCueMSE];
gaussianMSE = [mean(gaussianCueMSE, 2), gaussianCueMSE];
improvement = stimMSE - gaussianMSE;
percentReduction = 100 .* improvement ./ stimMSE;
stimPooledR2 = pooledR2(stim);
gaussianPooledR2 = pooledR2(gaussian);
stimR2 = [stimPooledR2, stim.Nested.PerCueR2ByRepeat];
gaussianR2 = [gaussianPooledR2, gaussian.Nested.PerCueR2ByRepeat];
conditions = ["Equal-cue aggregate"; "Dominant"; "Combined"; "Stereo"; "NonDominant"];
repeatIndex = repmat((1:numRepeats)', 5, 1);
conditionIndex = repelem((1:5)', numRepeats);
repeats = table(repeatIndex, conditions(conditionIndex), ...
    stimMSE(:), gaussianMSE(:), improvement(:), percentReduction(:), ...
    stimR2(:), gaussianR2(:), reshape(gaussianR2 - stimR2, [], 1), ...
    improvement(:) > 0, 'VariableNames', ...
    {'Repeat', 'Condition', 'StimOnlyMSE', 'GaussianMSE', 'MSEImprovement', ...
    'PercentErrorReduction', 'StimOnlyCVR2', 'GaussianCVR2', ...
    'DeltaCVR2', 'GaussianImproved'});

splitQuantiles = prctile(improvement, [2.5 50 97.5], 1);
foldImprovement = stim.Nested.FoldMSE - gaussian.Nested.FoldMSE;
fractionFoldsImproved = reshape(mean(foldImprovement > 0, [1 2]), 5, 1);
summary = table(conditions, repmat(numRepeats, 5, 1), ...
    mean(stimMSE, 1)', mean(gaussianMSE, 1)', mean(improvement, 1)', ...
    std(improvement, 0, 1)', splitQuantiles(1, :)', splitQuantiles(2, :)', ...
    splitQuantiles(3, :)', sum(improvement > 0, 1)', mean(improvement > 0, 1)', ...
    fractionFoldsImproved, mean(percentReduction, 1)', ...
    mean(stimR2, 1)', mean(gaussianR2, 1)', mean(gaussianR2 - stimR2, 1)', ...
    'VariableNames', {'Condition', 'NumOuterRepeats', 'MeanStimOnlyMSE', ...
    'MeanGaussianMSE', 'MeanMSEImprovement', 'SplitSD', ...
    'SplitP2_5', 'SplitMedian', 'SplitP97_5', 'RepeatsImproved', ...
    'FractionRepeatsImproved', 'FractionOuterFoldsImproved', ...
    'MeanPercentErrorReduction', 'MeanStimOnlyCVR2', 'MeanGaussianCVR2', 'MeanDeltaCVR2'});

sigma = gaussian.Nested.SelectedSigma(:);
assert(all(isfinite(sigma)) && all(sigma > 0), ...
    'GaussianStimCV:RobustnessSigma', 'Every outer fold must select a finite positive sigma.');
sigmaQuantiles = prctile(sigma, [2.5 25 50 75 97.5]);
sigmaSummary = table(numel(sigma), min(sigma), sigmaQuantiles(1), ...
    sigmaQuantiles(2), sigmaQuantiles(3), sigmaQuantiles(4), sigmaQuantiles(5), ...
    max(sigma), nnz(sigma == min(gaussian.SigmaValues)), ...
    nnz(sigma == max(gaussian.SigmaValues)), ...
    'VariableNames', {'NumOuterFits', 'MinSigma', 'SigmaP2_5', ...
    'SigmaP25', 'MedianSigma', 'SigmaP75', 'SigmaP97_5', 'MaxSigma', ...
    'FitsAtLowerGridBoundary', 'FitsAtUpperGridBoundary'});
robustness = struct('RepeatMetrics', repeats, 'Summary', summary, ...
    'SigmaSummary', sigmaSummary);
robustness.Interpretation = [ ...
    "Each repeat scores all sessions once using outer held-out predictions"; ...
    "Split percentiles quantify sensitivity to random CV partitions, not population confidence intervals"; ...
    "Fraction of improved repeats is descriptive and is not a significance-test p-value"; ...
    "Repeated partitions reuse the same cohort; corrected paired inference is reported separately"];
end

function r2 = pooledR2(model)
modelSSE = sum((model.Observed - model.Nested.PredictionByRepeat).^2, 1);
nullSSE = sum((model.Observed - model.NullPredictionByRepeat).^2, 1);
r2 = (1 - modelSSE ./ nullSSE)';
end
