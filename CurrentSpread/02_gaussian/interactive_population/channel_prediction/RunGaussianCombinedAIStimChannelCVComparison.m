function analysis = RunGaussianCombinedAIStimChannelCVComparison(options)
%RUNGAUSSIANCOMBINEDAISTIMCHANNELCVCOMPARISON Test value of spatial pooling.
% Baseline: intercept + slope*predictor at the actual stimulation channel.
% Alternative: Gaussian-weighted channel predictions from the same predictor.
% Both fit two beta coefficients independently per cue. Compare the same
% held-out sessions; only the Gaussian model needs inner-CV sigma selection.

arguments
    options.CacheFile (1, 1) string = ...
        "C:\EM\CurrentSpread\02_gaussian\InteractiveGaussianMetaPopulation\MT\GaussianMetaPopulationSigmaCache.mat"
    options.OutputFolder (1, 1) string = ""
    options.UnitType (1, 1) string {mustBeMember(options.UnitType, ["2D", "3D"])} = "2D"
    options.SigmaValues (1, :) double = []
    options.NumRepeats (1, 1) double {mustBeInteger, mustBePositive} = 5
    options.NumFolds (1, 1) double {mustBeInteger, mustBeGreaterThan(options.NumFolds, 1)} = 5
    options.NumInnerFolds (1, 1) double {mustBeInteger, mustBeGreaterThan(options.NumInnerFolds, 1)} = 5
    options.RandomSeed (1, 1) double {mustBeInteger, mustBeNonnegative} = 1
    options.PredictorMode (1, 1) string ...
        {mustBeMember(options.PredictorMode, ...
        ["CombinedAI", "DominantAIxOD"])} = "DominantAIxOD"
end
loaded = load(options.CacheFile, 'cache');
cache = loaded.cache;
if strlength(options.OutputFolder) == 0
    options.OutputFolder = fullfile(cache.OutputFolder, options.UnitType, ...
        options.PredictorMode + '_GaussianVsStimOnly_CV');
    options.OutputFolder = options.OutputFolder + "_SourceStimBothEyes";
end
repositoryRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
outputFolder = string(char(java.io.File(char(options.OutputFolder)).getCanonicalPath()));
resolvedRoot = string(char(java.io.File(repositoryRoot).getCanonicalPath()));
if strcmpi(outputFolder, resolvedRoot) || startsWith(lower(outputFolder), lower(resolvedRoot + filesep))
    error('GaussianStimCV:RepositoryOutput', 'Outputs must be outside the repository: %s', outputFolder);
end
if ~isfolder(outputFolder)
    mkdir(outputFolder);
end
data = buildCombinedAIStimComparisonDesign(cache, ...
    UnitType=options.UnitType, SigmaValues=options.SigmaValues(:), ...
    PredictorMode=options.PredictorMode);
if data.SessionCount < 10
    error('GaussianStimCV:TooFewSessions', 'Fewer than ten matched sessions are available.');
end
mask = data.SessionMask;
sourceRows = data.SourceRows;
sigmaValues = data.SigmaValues;
y = data.Observed;
map = data.ObservationMap;
predictorLabel = predictorDisplayLabel(options.PredictorMode);
fprintf('Gaussian vs stim-only %s: %s %s, %d matched sessions, %d points, %d Gaussian channels.\n', ...
    predictorLabel, cache.Area, options.UnitType, data.SessionCount, ...
    numel(y), nnz(data.GaussianChannelMask));
fprintf('Excluded %d otherwise usable Gaussian sessions because the source neuron or stim input failed the both-eye gate.\n', ...
    nnz(data.SessionAudit.BaseCandidate & data.SessionAudit.HasEligibleGaussianChannel & ~mask));
args = {'NumRepeats', options.NumRepeats, 'NumFolds', options.NumFolds, ...
    'NumInnerFolds', options.NumInnerFolds, 'RandomSeed', options.RandomSeed};
fprintf('Evaluating exact stimulation-channel-only baseline...\n');
stim = crossValidateGaussianChannelDesign(data.StimDesign, y, map, 1, ...
    args{:}, TuneSigma=false);
fprintf('Evaluating Gaussian pooling with inner-CV sigma selection...\n');
gaussian = crossValidateGaussianChannelDesign(data.GaussianDesign, y, map, sigmaValues, args{:});
assert(isequal(stim.FoldAssignments, gaussian.FoldAssignments), ...
    'GaussianStimCV:UnmatchedFolds', 'Models must use identical outer session folds.');
assert(isequaln(stim.NullPredictionByRepeat, gaussian.NullPredictionByRepeat), ...
    'GaussianStimCV:UnmatchedNull', 'Models must share the cue-specific training-mean reference.');
assert(isequal(stim.Nested.PredictionByRepeat, stim.BestPredictionByRepeat), ...
    'GaussianStimCV:FixedBaselineMismatch', 'A fixed baseline must have the same predictions with or without inner CV.');
significance = compareGaussianChannelCVErrors(stim.Nested.FoldMSE, ...
    gaussian.Nested.FoldMSE, stim.Nested.FoldTestTrainRatio);
significance.Properties.VariableNames{'OldMeanFoldMSE'} = 'StimOnlyMeanFoldMSE';
significance.Properties.VariableNames{'NewMeanFoldMSE'} = 'GaussianMeanFoldMSE';
conditionNames = ["Dominant"; "Combined"; "Stereo"; "NonDominant"];
performance = table(conditionNames, stim.Nested.PerCueMeanMSE, gaussian.Nested.PerCueMeanMSE, ...
    stim.Nested.PerCueMeanR2, gaussian.Nested.PerCueMeanR2, ...
    gaussian.Nested.PerCueMeanR2 - stim.Nested.PerCueMeanR2, ...
    significance.PImprovementOneSided(2:5), significance.PImprovementHolmWithinCues(2:5), ...
    'VariableNames', {'Condition', 'StimOnlyNestedMSE', 'GaussianNestedMSE', ...
    'StimOnlyNestedCVR2', 'GaussianNestedCVR2', 'DeltaNestedCVR2', ...
    'PImprovement', 'PImprovementHolm'});
summary = table(["Stim-channel " + predictorLabel; ...
    "Gaussian " + predictorLabel], ...
    [8; 8], [stim.BestSigma; gaussian.BestSigma], [stim.BestCVMSE; gaussian.BestCVMSE], ...
    [stim.BestCVR2; gaussian.BestCVR2], [stim.Nested.MeanMSE; gaussian.Nested.MeanMSE], ...
    [stim.Nested.MeanPooledR2; gaussian.Nested.MeanPooledR2], ...
    'VariableNames', {'Model', 'BetaCount', 'SelectionCVBestSigma', ...
    'SelectionCV_MSE', 'SelectionCV_PooledR2', 'NestedCV_MSE', 'NestedCV_PooledR2'});
curve = table(sigmaValues, repmat(stim.MeanCVMSE, numel(sigmaValues), 1), ...
    gaussian.MeanCVMSE, repmat(stim.MeanCVR2, numel(sigmaValues), 1), gaussian.MeanCVR2, ...
    'VariableNames', {'Sigma', 'StimOnlySelectionCVMSE', 'GaussianSelectionCVMSE', ...
    'StimOnlySelectionCVR2', 'GaussianSelectionCVR2'});
for condition = 1:4
    curve.("StimOnlyCVMSE_" + conditionNames(condition)) = repmat(stim.PerCueMeanCVMSE(condition, 1), numel(sigmaValues), 1);
    curve.("GaussianCVMSE_" + conditionNames(condition)) = gaussian.PerCueMeanCVMSE(condition, :)';
    curve.("StimOnlyCVR2_" + conditionNames(condition)) = repmat(stim.PerCueMeanCVR2(condition, 1), numel(sigmaValues), 1);
    curve.("GaussianCVR2_" + conditionNames(condition)) = gaussian.PerCueMeanCVR2(condition, :)';
end
pointTable = map;
pointTable.SourceTableRow = sourceRows(map.SessionIndex);
monkey = string(cache.Monkey(mask));
pointTable.Monkey = monkey(map.SessionIndex);
pointTable.Observed = y;
pointTable.StimOnlyNestedPrediction = stim.Nested.MeanPrediction;
pointTable.GaussianNestedPrediction = gaussian.Nested.MeanPrediction;
pointTable.StimOnlyMeanSquaredError = mean((y - stim.Nested.PredictionByRepeat).^2, 2);
pointTable.GaussianMeanSquaredError = mean((y - gaussian.Nested.PredictionByRepeat).^2, 2);
foldTable = table();
for repeat = 1:options.NumRepeats
    for fold = 1:stim.NumFolds
        entry = table(repeat, fold, stim.Nested.SelectedSigma(repeat, fold), ...
            gaussian.Nested.SelectedSigma(repeat, fold), stim.Nested.FoldMSE(repeat, fold, 1), ...
            gaussian.Nested.FoldMSE(repeat, fold, 1), stim.Nested.FoldTestTrainRatio(repeat, fold, 1), ...
            'VariableNames', {'Repeat', 'Fold', 'StimOnlySigma', 'GaussianSigma', ...
            'StimOnlyMSE', 'GaussianMSE', 'TestTrainRatio'});
        foldTable = [foldTable; entry]; %#ok<AGROW>
    end
end
analysis = struct('SchemaVersion', 2, 'Created', datetime('now'), ...
    'CacheFile', options.CacheFile, 'OutputFolder', outputFolder, ...
    'Area', cache.Area, 'UnitType', options.UnitType, 'ODDefinition', cache.ODDefinition, ...
    'SourceRows', sourceRows, 'GaussianChannelMask', data.GaussianChannelMask, ...
    'StimChannelMask', data.StimChannelMask, 'SessionAudit', data.SessionAudit, ...
    'CohortDefinition', data.CohortDefinition, ...
    'SourceTuningP', data.SourceTuningP, ...
    'EffectiveChannelTuningP', data.EffectiveChannelTuningP, ...
    'RawChannelTuningP', data.RawChannelTuningP, ...
    'ChannelTuningSource', data.ChannelTuningSource, ...
    'SessionCount', nnz(mask), 'PredictorMode', options.PredictorMode, ...
    'PredictorLabel', predictorLabel, ...
    'StimOnly', stim, 'Gaussian', gaussian, ...
    'Summary', summary, 'PerCuePerformance', performance, ...
    'Significance', significance, 'SigmaCurve', curve, ...
    'Points', pointTable, 'OuterFoldAudit', foldTable);
analysis.FilePrefix = "Gaussian" + options.PredictorMode + ...
    "StimChannelCVComparison";
analysis.Method = [ ...
    "Same sessions, observed cues, eight beta coefficients, and identical session-grouped outer folds"; ...
    "Neuron inclusion: source unit_table_gof.p_AI(2)<alpha and p_AI(3)<alpha"; ...
    "Stimulation contact uses source p_AI; neighboring contacts use their own raw direction p-values"; ...
    "Predictor: " + predictorLabel; ...
    "Baseline: exact predictor at StimChannel; no sigma tuning"; ...
    "Gaussian: same predictor across eligible channels; sigma selected only within training data"; ...
    "Repeated CV: " + options.NumFolds + " folds x " + options.NumRepeats + " repeats; equal-cue MSE selects sigma"; ...
    "Nested CV: outer test excluded from both beta fitting and inner sigma selection"; ...
    "Primary significance: corrected paired t-test of stim-only minus Gaussian outer-fold equal-cue MSE"; ...
    "Correction: SE = sqrt((1/(repeats*folds) + mean(nTest/nTrain))*var(error differences))"; ...
    "One-sided improvement test; two-sided p and 95% CI also reported; per-cue tests Holm adjusted"; ...
    "Approximate uncertainty for repeated CV with overlapping training sets"; ...
    "https://scikit-learn.org/stable/auto_examples/model_selection/plot_grid_search_stats.html"];
analysis.Robustness = summarizeGaussianStimCVRobustness(stim, gaussian);
analysis.OverallR2SignedRank = SaveGaussianStimOverallR2Scatter( ...
    analysis, OutputFolder=outputFolder, PointColor=areaColor(cache.Area));
writetable(data.SessionAudit, fullfile(outputFolder, 'SessionInclusionAudit.csv'));
writetable(summary, fullfile(outputFolder, 'ModelSummary.csv'));
writetable(performance, fullfile(outputFolder, 'PerCuePerformance.csv'));
writetable(significance, fullfile(outputFolder, 'CorrectedPairedComparison.csv'));
writetable(curve, fullfile(outputFolder, 'SelectionCVCurves.csv'));
writetable(pointTable, fullfile(outputFolder, 'NestedHeldOutPredictions.csv'));
writetable(foldTable, fullfile(outputFolder, 'NestedFoldAudit.csv'));
writetable(analysis.Robustness.RepeatMetrics, fullfile(outputFolder, 'OuterRepeatMetrics.csv'));
writetable(analysis.Robustness.Summary, fullfile(outputFolder, 'OuterRepeatRobustness.csv'));
writetable(analysis.Robustness.SigmaSummary, fullfile(outputFolder, 'OuterSigmaRobustness.csv'));
save(fullfile(outputFolder, analysis.FilePrefix + '.mat'), ...
    'analysis', '-v7.3');
saveComparisonFigure(analysis);
saveRobustnessFigure(analysis);
manifest = ["Gaussian versus stimulation-channel-only CV comparison"; ...
    "Predictor: " + predictorLabel; ...
    "Area / class: " + cache.Area + " " + options.UnitType; ...
    "Sessions: " + nnz(mask); "Sigma values: " + numel(sigmaValues); ...
    "Repeats: " + options.NumRepeats; "Outer folds: " + options.NumFolds; ...
    "Inner folds: " + options.NumInnerFolds; "Random seed: " + options.RandomSeed; ...
    analysis.Method; analysis.Robustness.Interpretation; ...
    analysis.OverallR2SignedRank.Interpretation; ...
    "Outer repeats with lower Gaussian MSE: " + ...
        analysis.Robustness.Summary.RepeatsImproved(1) + "/" + options.NumRepeats; ...
    "Primary corrected improvement p = " + significance.PImprovementOneSided(1); ...
    "Primary MSE difference (stim-gaussian) = " + significance.MSEImprovement(1); ...
    "Primary difference 95% CI = [" + significance.ImprovementCILow(1) + ", " + ...
        significance.ImprovementCIHigh(1) + "]"];
writelines(manifest, fullfile(outputFolder, 'ComparisonManifest.txt'));
disp(summary); disp(performance); disp(significance);
disp(analysis.Robustness.Summary); disp(analysis.Robustness.SigmaSummary);
fprintf('CV comparison saved to: %s\n', outputFolder);
end

function label = predictorDisplayLabel(mode)
if mode == "DominantAIxOD"
    label = "dominant-eye AI x |OD|";
else
    label = "Combined AI";
end
end

function color = areaColor(area)
if strcmpi(area, "MT")
    color = [230 126 34] ./ 255;
else
    color = [151 78 163] ./ 255;
end
end

function saveRobustnessFigure(analysis)
f = figure('Visible', 'off', 'Color', 'w', 'Position', [80 80 1380 820]);
cleanup = onCleanup(@() close(f));
layout = tiledlayout(f, 2, 2, 'TileSpacing', 'compact');
color = [0.1 0.35 0.75];
repeatTable = analysis.Robustness.RepeatMetrics;
overall = repeatTable(repeatTable.Condition == "Equal-cue aggregate", :);
ax = nexttile(layout);
plot(ax, overall.Repeat, overall.MSEImprovement, 'o-', ...
    'Color', color, 'MarkerSize', 3); yline(ax, 0, 'k--');
xlabel(ax, 'Outer CV repeat'); ylabel(ax, 'Stim-only MSE - Gaussian MSE');
title(ax, sprintf('Improved in %d/%d complete outer repeats', ...
    nnz(overall.GaussianImproved), height(overall))); grid(ax, 'on');
ax = nexttile(layout);
histogram(ax, overall.MSEImprovement, 'FaceColor', color);
xline(ax, 0, 'k--', 'LineWidth', 1.2);
xlabel(ax, 'Stim-only MSE - Gaussian MSE'); ylabel(ax, 'Number of outer repeats');
title(ax, 'Split variability on the same sessions'); grid(ax, 'on');
ax = nexttile(layout);
summary = analysis.Robustness.Summary;
errorbar(ax, 1:5, summary.SplitMedian, summary.SplitMedian-summary.SplitP2_5, ...
    summary.SplitP97_5-summary.SplitMedian, 'o', 'Color', color, 'LineWidth', 1.5);
yline(ax, 0, 'k--'); xlim(ax, [0.5 5.5]);
ax.XTick = 1:5; ax.XTickLabel = {'All cues', 'Dom', 'Combined', 'Stereo', 'NonDom'};
ylabel(ax, 'MSE improvement');
title(ax, 'Median and 2.5-97.5% split range (not a CI)'); grid(ax, 'on');
ax = nexttile(layout);
histogram(ax, analysis.Gaussian.Nested.SelectedSigma(:), 'FaceColor', color);
xlabel(ax, 'Inner-CV selected sigma'); ylabel(ax, 'Number of outer folds');
title(ax, sprintf('Sigma stability across %d outer fits', ...
    numel(analysis.Gaussian.Nested.SelectedSigma))); grid(ax, 'on');
title(layout, sprintf('%s %s | %d repeats of %d-fold outer CV | N = %d', ...
    analysis.Area, analysis.UnitType, analysis.Gaussian.NumRepeats, ...
    analysis.Gaussian.NumFolds, analysis.SessionCount));
exportgraphics(f, fullfile(analysis.OutputFolder, 'OuterCVRobustness.png'), 'Resolution', 200);
savefig(f, fullfile(analysis.OutputFolder, 'OuterCVRobustness.fig'));
end

function saveComparisonFigure(analysis)
f = figure('Visible', 'off', 'Color', 'w', 'Position', [80 80 1380 820]);
cleanup = onCleanup(@() close(f));
layout = tiledlayout(f, 2, 2, 'TileSpacing', 'compact');
oldColor = [0.5 0.5 0.5]; newColor = [0.1 0.35 0.75];
ax = nexttile(layout);
semilogx(ax, analysis.Gaussian.SigmaValues, ...
    repmat(analysis.StimOnly.BestCVMSE, size(analysis.Gaussian.SigmaValues)), ...
    'Color', oldColor, 'LineWidth', 2); hold(ax, 'on');
semilogx(ax, analysis.Gaussian.SigmaValues, analysis.Gaussian.MeanCVMSE, ...
    'Color', newColor, 'LineWidth', 2);
xlabel(ax, 'Gaussian sigma'); ylabel(ax, 'Equal-cue held-out MSE');
title(ax, 'Gaussian CV selection versus fixed stim-channel baseline');
legend(ax, {'Stim-channel ' + analysis.PredictorLabel, ...
    'Gaussian ' + analysis.PredictorLabel}, 'Location', 'northwest'); grid(ax, 'on');
ax = nexttile(layout);
b = bar(ax, [analysis.StimOnly.Nested.PerCueMeanR2 analysis.Gaussian.Nested.PerCueMeanR2]);
b(1).FaceColor = oldColor; b(2).FaceColor = newColor;
ax.XTickLabel = cellstr(analysis.PerCuePerformance.Condition);
ylabel(ax, 'Nested held-out R^2'); title(ax, 'Paired outer-test performance');
legend(ax, {'Stim-channel ' + analysis.PredictorLabel, ...
    'Gaussian ' + analysis.PredictorLabel}, 'Location', 'northwest'); grid(ax, 'on');
ax = nexttile(layout);
test = analysis.Significance;
errorbar(ax, 1:5, test.MSEImprovement, test.MSEImprovement-test.ImprovementCILow, ...
    test.ImprovementCIHigh-test.MSEImprovement, 'o', 'Color', newColor, ...
    'LineWidth', 1.5, 'MarkerFaceColor', newColor);
yline(ax, 0, 'k--'); ax.XTick = 1:5; xlim(ax, [0.5 5.5]);
ax.XTickLabel = {'All cues', 'Dom', 'Combined', 'Stereo', 'NonDom'};
ylabel(ax, 'Stim-only MSE - Gaussian MSE (positive = improvement)');
title(ax, sprintf('Corrected 95%% CI | primary one-sided p = %.4g', test.PImprovementOneSided(1)));
grid(ax, 'on');
ax = nexttile(layout);
plot(ax, analysis.OuterFoldAudit.GaussianSigma, 'o-', 'Color', newColor);
ax.YScale = 'log'; xlabel(ax, 'Outer evaluation fold'); ylabel(ax, 'Inner-CV selected sigma');
title(ax, 'Gaussian sigma selected in each training set'); grid(ax, 'on');
title(layout, sprintf('%s %s | matched CV comparison | N = %d sessions', ...
    analysis.Area, analysis.UnitType, analysis.SessionCount));
exportgraphics(f, fullfile(analysis.OutputFolder, ...
    analysis.FilePrefix + '.png'), 'Resolution', 200);
savefig(f, fullfile(analysis.OutputFolder, analysis.FilePrefix + '.fig'));
end
