function values = extractNumericScalars(column)
values = nan(numel(column), 1);
if iscell(column)
    for row = 1:numel(column)
        value = column{row};
        if isnumeric(value) && isscalar(value), values(row) = value; end
    end
else
    values = double(column(:));
end
end


function value = valueAt(values, row, fallback)
if isempty(row), value = fallback; else, value = values(row); end
end


function hash = fileSHA256(filePath)
sha = System.Security.Cryptography.SHA256.Create();
stream = System.IO.File.OpenRead(char(filePath));
cleanup = onCleanup(@() stream.Close());
bytes = sha.ComputeHash(stream);
hash = string(char(System.BitConverter.ToString(bytes)));
hash = erase(hash, '-');
clear cleanup
end


function makeFolder(folder)
if ~isfolder(folder), mkdir(folder); end
end


function closeFigureStruct(figures)
if ~isstruct(figures), return, end
names = fieldnames(figures);
for index = 1:numel(names)
    handles = figures.(names{index});
    for handleIndex = 1:numel(handles)
        closeValidFigure(handles(handleIndex));
    end
end
end


function closeValidFigure(handle)
if ~isempty(handle) && all(isgraphics(handle, 'figure')), close(handle); end
end
